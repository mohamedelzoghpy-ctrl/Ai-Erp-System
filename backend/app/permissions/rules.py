_RULES_BY_METHOD: Dict[str, List[RouteRule]] = {}
for _r in ROUTE_RULES:
    _RULES_BY_METHOD.setdefault(_r.method, []).append(_r)


def match_rule(method: str, path: str) -> Optional[RouteRule]:
    """أول قاعدة تطابق (method, path) — القواعد متمايزة فلا التباس."""
    for rule in _RULES_BY_METHOD.get(method.upper(), ()):
        if rule.matches(method.upper(), path):
            return rule
    return None

