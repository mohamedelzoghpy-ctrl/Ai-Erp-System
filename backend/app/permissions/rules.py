@dataclass(frozen=True)
class RouteRule:
    method: str
    pattern: str
    perms: Tuple[str, ...] = ()
    regex: object = dc_field(default=None, compare=False)

    def __post_init__(self):
        object.__setattr__(self, "regex", _pattern_to_regex(self.pattern))

    def matches(self, method: str, path: str) -> bool:
        if self.method != method:
            return False
        return self.regex.fullmatch(path) is not None  # type: ignore[union-attr]


def _pattern_to_regex(pattern: str):
    """يحوّل /products/{product_id} إلى regex يطابق المسار الفعلي."""
    return re.compile(re.sub(r"\{[^}]+\}", r"[^/]+", pattern) + r"/?")


def _rule(method: str, pattern: str, *perms: str) -> RouteRule:
    unknown = [p for p in perms if p not in KNOWN_CODES]
    if unknown:
        raise ValueError(f"Unknown permission codes in route rule: {unknown}")
    return RouteRule(method=method.upper(), pattern=pattern, perms=tuple(perms))


